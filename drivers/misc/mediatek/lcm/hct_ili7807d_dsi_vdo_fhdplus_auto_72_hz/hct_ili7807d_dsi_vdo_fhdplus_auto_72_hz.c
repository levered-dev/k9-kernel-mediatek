static void lcm_init(void)
{
	MDELAY(10);
	display_bias_enable();
	MDELAY(15);

	SET_RESET_PIN(1);
	MDELAY(5);
	SET_RESET_PIN(0);
	MDELAY(10);
	SET_RESET_PIN(1);
	MDELAY(120);

	push_table(lcm_initialization_setting,
		ARRAY_SIZE(lcm_initialization_setting), 1);
}

static void lcm_suspend(void)
{
	unsigned int data_array[1];

	data_array[0] = 0x00280500;
	dsi_set_cmdq(data_array, 1, 1);
	MDELAY(20);
	data_array[0] = 0x00100500;
	dsi_set_cmdq(data_array, 1, 1);
	MDELAY(120);

	SET_RESET_PIN(0);
	MDELAY(20);
	display_bias_disable();
	MDELAY(20);
}

static void lcm_resume(void)
{
	lcm_init();
}

static unsigned int lcm_compare_id(void)
{
	unsigned int data_array[2];
	unsigned char id0 = 0;
	unsigned char id1 = 0;
	unsigned char id2 = 0;
	unsigned int id;

	SET_RESET_PIN(1);
	MDELAY(20);
	SET_RESET_PIN(0);
	MDELAY(20);
	SET_RESET_PIN(1);
	MDELAY(120);

	data_array[0] = 0x00043902;
	data_array[1] = 0x010778FF;
	dsi_set_cmdq(data_array, 2, 1);
	MDELAY(10);

	data_array[0] = 0x00033700;
	dsi_set_cmdq(data_array, 1, 1);
	read_reg_v2(0x00, &id0, 1);
	read_reg_v2(0x01, &id1, 1);
	read_reg_v2(0x02, &id2, 1);
	id = (id0 << 16) | (id1 << 8) | id2;

	pr_info("ILI7807D compare:0x%02x,0x%02x,0x%02x,0x%06x\n",
		id0, id1, id2, id);
	return id == LCM_ID;
}

